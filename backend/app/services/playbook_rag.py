class PlaybookRAG:
    def search(self, query: str, top_k: int = 2) -> list[dict[str, Any]]:
        query_words = set(re.findall(r"\w+", query.lower()))
        scores = []
        for art in PLAYBOOK_ARTICLES:
            score = 0
            # Match title
            for w in query_words:
                if w in art["title"].lower():
                    score += 3
                if any(w in t.lower() for t in art["tags"]):
                    score += 4
                if w in art["content"].lower():
                    score += 1
            if score > 0:
                scores.append((score, art))
        
        scores.sort(key=lambda x: x[0], reverse=True)
        return [art for _, art in scores[:top_k]]

playbook_rag = PlaybookRAG()
