class PlaybookRAG:
    def search(self, query: str, top_k: int = 2) -> list[dict[str, Any]]:
        raw_words = re.findall(r"[a-zA-Zа-яА-ЯёЁ0-9_\-\.\:]+", query.lower())
        query_words = [w for w in raw_words if len(w) >= 2 and w not in STOP_WORDS]
        if not query_words:
            return []

        lower_query = query.lower().strip()
        scores = []

        for art in PLAYBOOK_ARTICLES:
            score = 0
            title_lower = art["title"].lower()
            tags = [t.lower() for t in art["tags"]]
            content_lower = art["content"].lower()

            # Exact phrase match in title or tags is highest priority
            for tag in tags:
                if tag in lower_query or lower_query in tag:
                    score += 15

            # Word matching with weighting
            for w in query_words:
                if w in title_lower:
                    score += 8
                elif len(w) >= 5 and w[:5] in title_lower:
                    score += 5

                for t in tags:
                    if w == t or w in t or t in w:
                        score += 6
                        break
                    elif len(w) >= 4 and len(t) >= 4 and (w[:4] == t[:4]):
                        score += 5
                        break

                if f" {w} " in f" {content_lower} ":
                    score += 2
                elif len(w) >= 5 and w[:5] in content_lower:
                    score += 1

            # Only consider articles with relevant score
            if score >= 6:
                scores.append((score, art))

        scores.sort(key=lambda x: x[0], reverse=True)
        return [art for _, art in scores[:top_k]]

